    FROM FACT_COUPON_METRIC fcm
    LEFT JOIN DIM_BILLING_CARRIER_POINT_CALCULATION dbcpc
      ON fcm.COUPON_ID = dbcpc.COUPON_ID
    QUALIFY(ROW_NUMBER() OVER(PARTITION BY fcm.COUPON_ID ORDER BY fcm.COUPON_ID, dbcpc.SCDEFFECTIVEDATETIME DESC))=1
  ) f_cpn

-- =========================================================================
-- JOIN TO DIM_COUPON (required - defines the grain)
-- =========================================================================
INNER JOIN
  (SELECT * FROM DIM_COUPON QUALIFY(ROW_NUMBER() OVER(PARTITION BY COUPON_ID ORDER BY SCDEFFECTIVEDATETIME DESC))=1)d_cpn
    ON f_cpn.COUPON_ID = d_cpn.COUPON_ID
    -- AND d_cpn.CURRENTFLAG = TRUE

-- =========================================================================
-- JOIN TO DIM_JOURNEY (required - includes eligibility filter)
-- =========================================================================
INNER JOIN DIM_JOURNEY d_jny
    ON d_cpn.JOURNEY_ID = d_jny.JOURNEY_ID
    -- AND d_jny.CURRENTFLAG = TRUE
    AND d_jny.JOURNEY_ELIGIBILITY = 'ELIGIBLE'

-- =========================================================================
-- JOIN TO DIM_DOCUMENT_DETAIL
-- =========================================================================
INNER JOIN
  (SELECT * FROM DIM_DOCUMENT_DETAIL QUALIFY(ROW_NUMBER() OVER(PARTITION BY JOURNEY_ID ORDER BY SCDEFFECTIVEDATETIME DESC))=1)d_doc
    ON d_jny.JOURNEY_ID = d_doc.JOURNEY_ID
    -- AND d_doc.CURRENTFLAG = TRUE

-- =========================================================================
-- JOIN TO DIM_PASSENGER (via DIM_COUPON)
-- =========================================================================
INNER JOIN
  (SELECT * FROM DIM_PASSENGER QUALIFY(ROW_NUMBER() OVER(PARTITION BY JOURNEY_ID ORDER BY SCDEFFECTIVEDATETIME DESC))=1) d_pas
    ON d_doc.DOCUMENT_ID = d_pas.DOCUMENT_ID
    -- AND d_pas.CURRENTFLAG = TRUE

-- =========================================================================
-- JOIN TO DIM_SEGMENT
-- =========================================================================
LEFT JOIN
  (SELECT * FROM DIM_SEGMENT QUALIFY(ROW_NUMBER() OVER(PARTITION BY COUPON_ID ORDER BY SCDEFFECTIVEDATETIME DESC))=1)d_seg
    ON f_cpn.COUPON_ID = d_seg.COUPON_ID
    -- AND d_seg.CURRENTFLAG = TRUE

-- =========================================================================
-- JOIN TO DIM_CREDITING_INVOICE_DETAIL (LEFT JOIN - may not exist for all coupons)
-- =========================================================================
LEFT JOIN
  (SELECT * FROM DIM_CREDITING_INVOICE_DETAIL QUALIFY(ROW_NUMBER() OVER(PARTITION BY COUPON_ID ORDER BY SCDEFFECTIVEDATETIME DESC))=1) d_cid
    ON f_cpn.COUPON_ID = d_cid.COUPON_ID
    -- AND d_cid.CURRENTFLAG = TRUE

-- =========================================================================
-- JOIN TO DIM_BILLING_CARRIER_POINT_CALCULATION (LEFT JOIN - may not exist for all coupons)
-- =========================================================================
LEFT JOIN
  (SELECT * FROM DIM_BILLING_CARRIER_POINT_CALCULATION QUALIFY(ROW_NUMBER() OVER(PARTITION BY COUPON_ID ORDER BY SCDEFFECTIVEDATETIME DESC))=1) d_bcpc
    ON f_cpn.COUPON_ID = d_bcpc.COUPON_ID
    -- AND d_bcpc.CURRENTFLAG = TRUE

) SELECT * FROM CTE_QUERY
ORDER BY
    COUPON_ID,
    JOURNEY_ID,
    DOCUMENT_ID,
    SEGMENT_ID
