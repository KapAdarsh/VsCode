CREATE OR REPLACE PROCEDURE EDW_DEV.EDW_CUSTOMER_360_REPORT.C360_SEARCH()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    err_msg STRING;
BEGIN
    -- Step 1: Clone the target table
    CREATE OR REPLACE TABLE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_CLONE 
    CLONE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH;

    -- Step 2: Delete data for the last 2 years
    DELETE FROM EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_CLONE 
    WHERE PNR_CRT_DTE >= DATEADD(YEAR, -2, CURRENT_DATE);

    -- Step 3: Add clustering
    ALTER TABLE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_CLONE
    CLUSTER BY (PNR_LOC, PSGR_NME);

    -- Step 4: Add search optimization
    ALTER TABLE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_CLONE
    ADD SEARCH OPTIMIZATION ON EQUALITY(PNR_LOC, PSGR_NME);

    -- Step 5: Insert data
    INSERT INTO EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_CLONE
    SELECT DISTINCT
        P.PNR_LOC,
        TO_CHAR(P.PNR_CRT_DTE, ''YYYY-MM-DD'') AS PNR_CRT_DTE,
        UPPER(P.PSGR_LAST_NME) AS PSGR_LAST_NME,
        UPPER(P.PSGR_FIRST_NME) AS PSGR_FIRST_NME,
        S.SEG_OPER_FLT_NUM,
        TO_CHAR(TO_DATE(S.SEG_DEP_LCL_DTE_TME), ''YYYY-MM-DD'') AS DEP_LCL_DATE,
        UPPER(CE.CONTACT_CLEANED) AS EMAIL,
        PT.TKT_NUM,
        UPPER(MEMBERSHIP_ID) AS AEROPLAN_NUM,
        CONCAT(TRIM(UPPER(P.PSGR_FIRST_NME)), '' '', TRIM(UPPER(P.PSGR_LAST_NME))) AS PSGR_NME,
        LOYALTY_REQ.LOYALTY_CDE AS LOYALTY_CDE,
        ''C360_SEARCH_REPORT'' AS CREATED_BY,
        ''SNOWFLAKE'' AS LOADED_BY,
        CURRENT_TIMESTAMP() AS LOADED_TMS
    FROM EDW_UAT.ev.pnr_seg S
    INNER JOIN EDW_UAT.ev.pnr_psgr P
        ON S.PNR_ID = P.PNR_ID AND S.PNR_VER = P.PNR_VER
    LEFT OUTER JOIN (
        SELECT DISTINCT PNR_ID, CONTACT_CLEANED
        FROM EDW_UAT.ev.pnr_contact
        WHERE CONTACT_TYP = ''EMAIL''
          AND PNR_CRT_DTE >= DATEADD(YEAR, -5, CURRENT_DATE)
          AND IS_CURRENT_FLG = ''Y''
    ) CE ON P.PNR_ID = CE.PNR_ID
    LEFT OUTER JOIN (
        SELECT DISTINCT PNR_ID, TKT_NUM, TKT_PSGR_ID
        FROM EDW_UAT.ev.pnr_tkt_ref
        WHERE TKT_DOC_TYP IN (''ETICKET'',''TICKET'')
          AND TKT_NUM IS NOT NULL
          AND PNR_CRT_DTE >= DATEADD(YEAR, -5, CURRENT_DATE)
    ) PT ON S.PNR_ID = PT.PNR_ID AND P.PSGR_ID = PT.TKT_PSGR_ID
    LEFT OUTER JOIN (
        SELECT
            SEG.VALUE:ID::STRING AS SEG_ID_JOIN,
            PAX.VALUE:ID::STRING AS PAX_ID_JOIN,
            PNR_ID,
            MEMBERSHIP_ID,
            LOYALTY_CDE
        FROM EDW_UAT.ev.pnr_loyalty_request B,
             LATERAL FLATTEN(INPUT => LOYALTY_PRODUCT:COLLECTION, OUTER => TRUE) SEG,
             LATERAL FLATTEN(INPUT => LOYALTY_PSGR:COLLECTION, OUTER => TRUE) PAX
        WHERE IS_CURRENT_FLG = ''Y''
          AND PNR_CRT_DTE >= DATEADD(YEAR, -5, CURRENT_DATE)
          AND LOYALTY_CDE IN (''FQTV'', ''FQTR'')
          AND MEMBERSHIP_ACTIVE_TIER_CO_CDE = ''AC''
    ) LOYALTY_REQ
        ON LOYALTY_REQ.PNR_ID = S.PNR_ID
       AND LOYALTY_REQ.SEG_ID_JOIN = S.PRODUCT_ID
       AND LOYALTY_REQ.PAX_ID_JOIN = P.PSGR_ID
    WHERE P.PNR_CRT_DTE >= DATEADD(YEAR, -5, CURRENT_DATE)
      AND S.PNR_CRT_DTE >= DATEADD(YEAR, -5, CURRENT_DATE)
      AND P.IS_CURRENT_FLG = ''Y''
    ORDER BY
        P.PNR_LOC,
        TO_CHAR(P.PNR_CRT_DTE, ''YYYY-MM-DD''),
        TO_CHAR(TO_DATE(S.SEG_DEP_LCL_DTE_TME), ''YYYY-MM-DD''),
        PT.TKT_NUM,
        UPPER(MEMBERSHIP_ID),
        UPPER(CE.CONTACT_CLEANED),
        UPPER(P.PSGR_FIRST_NME),
        UPPER(P.PSGR_LAST_NME),
        S.SEG_OPER_FLT_NUM;

    -- Step 6: Rename old table
    ALTER TABLE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH 
    RENAME TO EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_BKP;

    -- Step 7: Rename new table
    ALTER TABLE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_CLONE 
    RENAME TO EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH;

    -- Step 8: Drop backup table
    DROP TABLE IF EXISTS EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_BKP;

    RETURN ''SUCCESS'';

    EXCEPTION
    WHEN ERROR THEN
        -- Attempt rollback if error occurs
        BEGIN
            -- Drop the failed new version if it exists
            EXECUTE IMMEDIATE ''DROP TABLE IF EXISTS EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH'';

            -- Restore backup if available
            BEGIN
                EXECUTE IMMEDIATE ''ALTER TABLE EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH_BKP RENAME TO EDW_dev.EDW_CUSTOMER_360_REPORT.C360_SEARCH'';
            EXCEPTION
                WHEN STATEMENT_ERROR THEN
                    -- Backup doesn''t exist, nothing to restore
                    NULL;
            END;

            RETURN ''FAILURE'';
        END;

END;
';