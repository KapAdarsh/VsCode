MERGE INTO EDW.FACT_MEMBERPREFERENCE TARGET
USING ( 
-- Join Transform table with Dimension to get the SIDs and match the Fact table structure
WITH TransformTable as (
  SELECT
      COALESCE(DT2.MEMBERSID, -1) AS MEMBERSID,
  COALESCE(DIM_DATE.DATESID, -1) AS PREFERENCEMODIFIEDDATESID,
  COALESCE(DT3.MEMBERPREFERENCESID, -1) AS MEMBERPREFERENCESID,
  TFT.PREFERENCECODE,
  TFT.PREFERENCETYPECODE,
  PREFERENCECONTEXT,
  TFT.DOCUMENTVERSIONNUMBER,
  TFT.PREFERENCEFLAG,
  TFT.PREFERENCEMODIFIEDTIMESTAMP,
  COALESCE(TFT.MEMBERHASHKEY, '') AS MEMBERHASHKEY,
  COALESCE(TFT.FACTHASH, '') AS FACTHASH,
    ROW_NUMBER() OVER (
      PARTITION BY TFT.MEMBERHASHKEY,
      DT3.MEMBERPREFERENCESID,
      TFT.PREFERENCEFLAG
      ORDER BY
        PREFERENCEMODIFIEDTIMESTAMP DESC
    ) AS rn
  FROM
    TRANSFORM.FACT_MEMBERPREFERENCE AS TFT
    LEFT JOIN EDW.Dim_Member AS DT2 ON (DT2.MEMBERNUMBER = TFT.MEMBERNUMBER)
    AND (
      TFT.SCDEFFECTIVEDATETIME BETWEEN DT2.SCDStartDateTime
      AND DT2.SCDEndDateTime
    )
    LEFT JOIN EDW.DIM_DATE AS DIM_DATE ON CAST(TFT.PREFERENCEMODIFIEDTIMESTAMP AS DATE) = DIM_DATE.FULLDATE
    LEFT JOIN EDW.DIM_MEMBERPREFERENCE AS DT3 ON (
      TRIM(DT3.PREFERENCECODE) = TRIM(TFT.PREFERENCECODE)
    )
    AND (
      TRIM(DT3.PREFERENCETYPECODE) = TRIM(TFT.PREFERENCETYPECODE)
    )
    AND (
      TFT.SCDEFFECTIVEDATETIME BETWEEN DT3.SCDStartDateTime
      AND DT3.SCDEndDateTime
    )
)
,TransformTable_Dedup AS ( 
-- Deduplicate the CTE TransformTable to get only the latest record per Member, PreferenceCode , Flag
Select * from TransformTable where rn=1
)
,combined AS (
-- Records combined from bot Fact Table and CTE tranform table
SELECT T.MemberSID,T.PREFERENCEMODIFIEDDATESID,T.MEMBERPREFERENCESID,D.PREFERENCECODE,D.PREFERENCETYPECODE,T.PREFERENCECONTEXT,T.DOCUMENTVERSIONNUMBER,T.PREFERENCEFLAG,T.PREFERENCEMODIFIEDTIMESTAMP,T.MEMBERHASHKEY,T.FACTHASH
FROM EDW.FACT_MEMBERPREFERENCE T
Left JOIN EDW.DIM_MEMBERPREFERENCE D
ON T.MEMBERPREFERENCESID = D.MEMBERPREFERENCESID
  UNION ALL
SELECT MemberSID,PREFERENCEMODIFIEDDATESID,MEMBERPREFERENCESID,PREFERENCECODE,PREFERENCETYPECODE,PREFERENCECONTEXT,DOCUMENTVERSIONNUMBER,PREFERENCEFLAG,PREFERENCEMODIFIEDTIMESTAMP,MEMBERHASHKEY,FACTHASH
FROM TransformTable 

)
,changes AS (
-- Detecting the records were the PREFERENCEFLAG changed compared to the last record
  SELECT
    MemberSID,
    PREFERENCEMODIFIEDDATESID,
    MEMBERHASHKEY,
    MEMBERPREFERENCESID,
    PREFERENCECODE,
    PREFERENCETYPECODE,
    PREFERENCECONTEXT,
    DOCUMENTVERSIONNUMBER,
    PREFERENCEFLAG,
    PREFERENCEMODIFIEDTIMESTAMP,
    FACTHASH,
    LAG(PREFERENCEFLAG) OVER (
      PARTITION BY MEMBERHASHKEY, PREFERENCECODE,PREFERENCETYPECODE
      ORDER BY PREFERENCEMODIFIEDTIMESTAMP
    ) AS prev_Flag
  FROM combined
)
,changed_rows AS (
-- Filtering to get only the records were a change occured
  SELECT
    MemberSID,
    PREFERENCEMODIFIEDDATESID,
    MEMBERHASHKEY,
    MEMBERPREFERENCESID,
    PREFERENCECODE,
    PREFERENCETYPECODE,
    PREFERENCECONTEXT,
    DOCUMENTVERSIONNUMBER,
    PREFERENCEFLAG,
    PREFERENCEMODIFIEDTIMESTAMP,
    FACTHASH
  FROM changes
  WHERE PREFERENCEFLAG != prev_Flag OR prev_Flag IS NULL
)
,finaltable as (
-- Group the records that have a change in flag to get the latest Timestamp
SELECT
    MEMBERHASHKEY,
    MEMBERPREFERENCESID,
    PREFERENCECODE,
    PREFERENCETYPECODE,
    PREFERENCEFLAG,
  MAX(PREFERENCEMODIFIEDTIMESTAMP) AS PREFERENCEMODIFIEDTIMESTAMP
FROM changed_rows
GROUP BY MEMBERHASHKEY, MEMBERPREFERENCESID,PREFERENCECODE,PREFERENCETYPECODE, PREFERENCEFLAG
)
-- Join the dedup tranform table and the the CTE final table to group records were no change occured 
--and records where the flag changed compared to the last one 
-- THEN MERGE with the Fact_Memberpreference
Select Distinct COALESCE(M.MemberSID, -1) AS MEMBERSID,COALESCE(CH.PREFERENCEMODIFIEDDATESID,T.PREFERENCEMODIFIEDDATESID) as PREFERENCEMODIFIEDDATESID ,T.MEMBERPREFERENCESID,T.PREFERENCECODE,T.PREFERENCETYPECODE,
COALESCE(CH.PREFERENCECONTEXT,T.PREFERENCECONTEXT) as PREFERENCECONTEXT,COALESCE(CH.DOCUMENTVERSIONNUMBER,T.DOCUMENTVERSIONNUMBER) as DOCUMENTVERSIONNUMBER,COALESCE(CH.PREFERENCEFLAG,T.PREFERENCEFLAG) as PREFERENCEFLAG,COALESCE(CH.PREFERENCEMODIFIEDTIMESTAMP,T.PREFERENCEMODIFIEDTIMESTAMP) as PREFERENCEMODIFIEDTIMESTAMP,T.MEMBERHASHKEY,T.FACTHASH
from TransformTable_Dedup T LEFT JOIN (
Select distinct C.PREFERENCEMODIFIEDDATESID,f.MEMBERPREFERENCESID,f.PREFERENCECODE,f.PREFERENCETYPECODE,C.PREFERENCECONTEXT,C.DOCUMENTVERSIONNUMBER,f.PREFERENCEFLAG,f.PREFERENCEMODIFIEDTIMESTAMP,f.MEMBERHASHKEY,C.FACTHASH
from finaltable f 
left join changed_rows C
on f.MEMBERHASHKEY = C.MEMBERHASHKEY and DATEDIFF(second,f.PREFERENCEMODIFIEDTIMESTAMP,C.PREFERENCEMODIFIEDTIMESTAMP)=0 
and f.MEMBERPREFERENCESID = C.MEMBERPREFERENCESID and f.PREFERENCEFLAG = C.PREFERENCEFLAG ) CH 
on T.MEMBERHASHKEY = CH.MEMBERHASHKEY AND T.MEMBERPREFERENCESID = CH.MEMBERPREFERENCESID and T.PREFERENCEFLAG = CH.PREFERENCEFLAG
LEFT JOIN EDW.Dim_Member AS M ON (M.MEMBERHASHKEY = T.MEMBERHASHKEY)
    AND (
      COALESCE(CH.PREFERENCEMODIFIEDTIMESTAMP,T.PREFERENCEMODIFIEDTIMESTAMP) BETWEEN M.SCDStartDateTime
      AND M.SCDEndDateTime
    )
) AS SOURCE 
ON       TARGET.MEMBERHASHKEY = SOURCE.MEMBERHASHKEY 
       AND TARGET.MEMBERPREFERENCESID = SOURCE.MEMBERPREFERENCESID
       AND TARGET.PREFERENCEFLAG = SOURCE.PREFERENCEFLAG
WHEN MATCHED   THEN
-- Update the existing record in case it is a match
UPDATE SET   TARGET.MEMBERSID                              =         SOURCE.MEMBERSID
            ,TARGET.PREFERENCEMODIFIEDDATESID              =         SOURCE.PREFERENCEMODIFIEDDATESID
            ,TARGET.MEMBERPREFERENCESID                    =         SOURCE.MEMBERPREFERENCESID
            ,TARGET.PREFERENCECONTEXT                      =         SOURCE.PREFERENCECONTEXT 
            ,TARGET.DOCUMENTVERSIONNUMBER                  =         SOURCE.DOCUMENTVERSIONNUMBER 
            ,TARGET.PREFERENCEFLAG                         =         SOURCE.PREFERENCEFLAG 
            ,TARGET.PREFERENCEMODIFIEDTIMESTAMP            =         SOURCE.PREFERENCEMODIFIEDTIMESTAMP 
            ,TARGET.MEMBERHASHKEY                          =         SOURCE.MEMBERHASHKEY
            ,TARGET.UPDATEBATCHLOGID                       =         {BatchLogID}
            ,TARGET.UpdateType                             =        'UpdateCount'
            ,TARGET.FACTHASH                               =         SOURCE.FACTHASH
 
 
            
WHEN NOT MATCHED  THEN  
-- New Insert to EDW table in case there is no match
  INSERT (

          MEMBERSID, 
          PREFERENCEMODIFIEDDATESID,
          MEMBERPREFERENCESID ,
          PREFERENCECONTEXT,
          DOCUMENTVERSIONNUMBER,
          PREFERENCEFLAG,
          PREFERENCEMODIFIEDTIMESTAMP,
          MEMBERHASHKEY,
          FACTHASH,
          CREATEBATCHLOGID,
          UPDATEBATCHLOGID,
          UPDATETYPE
         )
  VALUES
         (
          MEMBERSID 
          ,PREFERENCEMODIFIEDDATESID
          ,MEMBERPREFERENCESID 
          ,PREFERENCECONTEXT
          ,DOCUMENTVERSIONNUMBER
          ,PREFERENCEFLAG
          ,PREFERENCEMODIFIEDTIMESTAMP
          ,MEMBERHASHKEY
          ,FACTHASH
          ,{BatchLogID}
          , -1
          ,'NewInsertCount'
         )            
            ; 
-- Creating a temp table to check if a record that was inserted due to a difference in MemberpreferenceSID for the same Preferencecode 
-- and created a duplicate           
CREATE OR REPLACE TEMPORARY TABLE AfterMerge AS
SELECT
  F.MEMBERHASHKEY,
  F.MEMBERPREFERENCESID,
  D.PREFERENCECODE,
  D.PREFERENCETYPECODE,
  F.PREFERENCEFLAG,
  F.PREFERENCEMODIFIEDDATESID,
  F.PREFERENCEMODIFIEDTIMESTAMP,
  ROW_NUMBER() OVER (
    PARTITION BY F.MEMBERHASHKEY,
    D.PREFERENCECODE,
    D.PREFERENCETYPECODE,
    F.PREFERENCEFLAG
    ORDER BY
      F.PREFERENCEMODIFIEDTIMESTAMP DESC
  ) AS rn
FROM
  EDW.FACT_MEMBERPREFERENCE AS F
  LEFT JOIN EDW.DIM_MEMBERPREFERENCE AS D ON F.MEMBERPREFERENCESID = D.MEMBERPREFERENCESID;
-- Update the record that should remain with update type as UpdateCount 
UPDATE
  EDW.FACT_MEMBERPREFERENCE AS F
SET
  UPDATETYPE = 'UpdateCount',
  UPDATEBATCHLOGID = {BatchLogID}
FROM
  (
    SELECT
      DISTINCT A1.MEMBERHASHKEY,
      A1.MEMBERPREFERENCESID,
      A1.PREFERENCEMODIFIEDDATESID,
      A1.PREFERENCEFLAG
    FROM
      AfterMerge AS A1
    WHERE
      EXISTS (
        SELECT
          1
        FROM
          AfterMerge AS A2
        WHERE
          A2.MEMBERHASHKEY = A1.MEMBERHASHKEY
          AND A2.PREFERENCECODE = A1.PREFERENCECODE
          AND A2.PREFERENCETYPECODE = A1.PREFERENCETYPECODE
          AND A2.PREFERENCEFLAG = A1.PREFERENCEFLAG
          AND A2.rn > 1
      )
      AND A1.rn = 1
  ) AS A
WHERE
  F.MEMBERHASHKEY = A.MEMBERHASHKEY
  AND F.MEMBERPREFERENCESID = A.MEMBERPREFERENCESID
  AND F.PREFERENCEMODIFIEDDATESID = A.PREFERENCEMODIFIEDDATESID
  AND F.PREFERENCEFLAG = A.PREFERENCEFLAG
  ;
-- Delete the duplicate records from The Fact_Memberpreference
DELETE FROM EDW.FACT_MEMBERPREFERENCE AS F USING AfterMerge AS A
WHERE
  F.MEMBERHASHKEY = A.MEMBERHASHKEY
  AND F.MEMBERPREFERENCESID = A.MEMBERPREFERENCESID
  AND F.PREFERENCEMODIFIEDDATESID = A.PREFERENCEMODIFIEDDATESID
  AND F.PREFERENCEFLAG = A.PREFERENCEFLAG
  AND A.rn > 1;
-- DROP The temporary table used 
  DROP TABLE IF EXISTS AfterMerge;
  