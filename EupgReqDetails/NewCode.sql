WITH 
-- Step 1: Get EUPG service requests (driving table)
SERVICE_REQUESTS AS (
    SELECT DISTINCT
        S.SERV_ID::VARCHAR(32)                                              AS SERVICE_REQUEST_ID,
        S.PNR_ID::VARCHAR(17)                                               AS PNR_UNIQUE_CODE,
        S.PNR_HASHKEY,
        psgr.value:id::VARCHAR(64)                                          AS PASSENGER_ID,
        pdt.value:id::VARCHAR(30)                                           AS PRODUCT_ID,
        TO_TIMESTAMP_NTZ(S.SERV_CREATION:dateTime::STRING)                  AS SERVICE_REQUEST_DATE_TIME,
        REGEXP_SUBSTR(S.SERV_TEXT, 'AC(\\d+)', 1, 1, 'e', 1)::VARCHAR(30)   AS SERVICE_REQUEST_MEMBER_NUMBER,
        REGEXP_SUBSTR(S.SERV_TEXT, '-([^/]+)', 1, 1, 'e', 1)::VARCHAR(14)   AS SERVICE_ORIGINAL_RBD,
        REGEXP_SUBSTR(S.SERV_TEXT, '-([^/]+)', 1, 2, 'e', 1)::VARCHAR(14)   AS SERVICE_TARGET_RBD,
         MAX(CASE WHEN S.is_deleted = 'Y' THEN VER_EFF_DTE_TME ELSE NULL END)
         OVER (PARTITION BY SERVICE_REQUEST_ID) AS SERVICE_REQUEST_DELETION_DATE_TIME
    FROM BDV.PIT_PNR_SERV S
    CROSS JOIN LATERAL FLATTEN(input => S.SERV_PRODUCT:collection) AS pdt
    CROSS JOIN LATERAL FLATTEN(input => S.SERV_PSGR:collection) AS psgr
    WHERE S.SERV_CDE = 'EUPG'

),

-- Step 2: Get distinct PNR keys for early filtering (derived from SERVICE_REQUESTS to avoid double scan)
EUPG_PNRS AS (
    SELECT DISTINCT PNR_HASHKEY FROM SERVICE_REQUESTS
),

-- Form of Payment - includes PNR_HASHKEY for proper join
FARE_ELEMENTS AS (
    SELECT DISTINCT
        Q.PNR_HASHKEY,
        Q.QUOTATION_CPN_PRICINGS_PRODUCT:id::VARCHAR(32)    AS SERV_ID,
        fe.value:id::VARCHAR(32)                            AS FOP_ID,
        Q.VER_EFF_DTE_TME                  AS FOP_EFFECTIVE_DATE_TIME
    FROM BDV.PIT_PNR_QUOTATION Q
    INNER JOIN EUPG_PNRS ep ON Q.PNR_HASHKEY = ep.PNR_HASHKEY
    CROSS JOIN LATERAL FLATTEN(input => Q.QUOTATION_FARE_ELEMENTS:collection) AS fe
    WHERE Q.IS_DELETED = 'N'
    AND fe.value:type = 'payment-method'
),

LATEST_FOP AS (
    SELECT 
        SERV_ID,
        FOP_ID AS LATEST_FOP_ID,
        PNR_HASHKEY,
    FROM FARE_ELEMENTS
    QUALIFY RANK() OVER (PARTITION BY SERV_ID ORDER BY FOP_EFFECTIVE_DATE_TIME DESC) = 1
),

-- Segments - ONLY for EUPG PNRs
SEGMENTS AS (
    SELECT DISTINCT
        S.PNR_HASHKEY,
        S.PRODUCT_ID::VARCHAR(30)               AS SEGMENT_CODE,
        psgr.value:id::VARCHAR(64)              AS PASSENGER_ID,
        S.SEG_STATUS::VARCHAR(2)                AS SEGMENT_STATUS_CODE,
        S.SEG_ORIG::VARCHAR(3)                  AS SEGMENT_ORIGIN,
        S.SEG_DEST::VARCHAR(3)                  AS SEGMENT_DESTINATION,
        S.SEG_LCL_DEP_DTE_TME                   AS SEGMENT_LOCAL_DEPARTURE_DATE_TIME,
        MAX_BY(S.SEG_LCL_ARR_DTE_TME, VER_EFF_DTE_TME) AS SEGMENT_LOCAL_ARRIVAL_DATE_TIME,
        MAX(S.seg_oper_carr_cde) AS SEGMENT_AIRLINE_CODE,
       MAX(S.seg_oper_flt_num) AS SEGMENT_FLIGHT_NUMBER,
        MIN(S.VER_EFF_DTE_TME)                  AS EFFECTIVE_DATE_TIME
    FROM BDV.PIT_PNR_SEG S
    INNER JOIN EUPG_PNRS ep ON S.PNR_HASHKEY = ep.PNR_HASHKEY
    CROSS JOIN LATERAL FLATTEN(input => S.SEG_PSGR:collection) AS psgr
    GROUP BY 
        S.PNR_HASHKEY,
        S.PRODUCT_ID,
        psgr.value:id,
        S.SEG_STATUS,
        S.SEG_ORIG,
        S.SEG_DEST,
        S.SEG_LCL_DEP_DTE_TME,
        S.IS_DELETED
),

-- Tickets - ONLY for EUPG PNRs
TICKETS AS (
    SELECT DISTINCT
        T.PNR_HASHKEY,
        T.TKT_PSGR_ID                   AS PASSENGER_ID,
        T.TKT_CPN_PRODUCT_ID            AS PRODUCT_ID,
        T.TKT_NUM::VARCHAR(14)          AS TICKET_NUMBER
    FROM BDV.PIT_PNR_TKT_REF T
    INNER JOIN EUPG_PNRS ep ON T.PNR_HASHKEY = ep.PNR_HASHKEY
    WHERE T.TKT_DOC_TYP = 'ETICKET'
      AND T.TKT_REF_TYP_ID IN ('FA', 'FHE')
      AND T.IS_DELETED = 'N'
),

-- Optimized PNR_HASHKEY
LOYALTY_FQTR AS (

SELECT DISTINCT
      R.PNR_HASHKEY,
      R.MEMBERSHIP_ID::VARCHAR(30) AS Redemption_Member_Number,
      psgr.value:id::string AS Passenger_ID
  FROM BDV.PIT_PNR_LOYALTY_REQUEST AS R
  INNER JOIN EUPG_PNRS ep ON R.PNR_HASHKEY = ep.PNR_HASHKEY
  CROSS JOIN LATERAL FLATTEN(input => R.LOYALTY_PSGR:collection) AS psgr
  WHERE R.LOYALTY_CDE = 'FQTR'
    AND R.IS_DELETED='N'
    AND R.MEMBERSHIP_ACTIVE_TIER_CO_CDE = 'AC'
    AND LENGTH(R.MEMBERSHIP_ID) = 9
),
-- Optimized PNR_HASHKEY
LOYALTY_FQTV AS (
SELECT DISTINCT
      R.PNR_HASHKEY,
      R.MEMBERSHIP_ID::VARCHAR(30) AS ACCRUAL_MEMBER_NUMBER,
      psgr.value:id::string AS Passenger_ID
  FROM BDV.PIT_PNR_LOYALTY_REQUEST AS R
  INNER JOIN EUPG_PNRS ep ON R.PNR_HASHKEY = ep.PNR_HASHKEY
  CROSS JOIN LATERAL FLATTEN(input => R.LOYALTY_PSGR:collection) AS psgr
  WHERE R.LOYALTY_CDE = 'FQTV'
    AND R.IS_DELETED='N'
    AND R.MEMBERSHIP_ACTIVE_TIER_CO_CDE = 'AC'
    AND LENGTH(R.MEMBERSHIP_ID) = 9
), EUPG_MAIN as(
SELECT DISTINCT
    sr.SERVICE_REQUEST_ID,
    sr.PASSENGER_ID,
    sr.SERVICE_REQUEST_DATE_TIME,
    sr.SERVICE_REQUEST_MEMBER_NUMBER,
    sr.SERVICE_ORIGINAL_RBD,
    sr.SERVICE_TARGET_RBD,
    sr.PNR_UNIQUE_CODE,
   FOP_EFFECTIVE_DATE_TIME,
    fe.FOP_ID AS SERVICE_REQUEST_FOP_ID,
    lf.LATEST_FOP_ID,
   sr.SERVICE_REQUEST_DELETION_DATE_TIME,
    seg.EFFECTIVE_DATE_TIME,
    seg.SEGMENT_CODE,
    seg.SEGMENT_STATUS_CODE,
    CASE 
        WHEN seg.SEGMENT_STATUS_CODE IN ('HK', 'KL', 'KK', 'TK') THEN 'Confirmed'
        WHEN seg.SEGMENT_STATUS_CODE IN ('UN', 'UC', 'HX')       THEN 'Lost'
        WHEN seg.SEGMENT_STATUS_CODE  IN ('TN', 'HN')            THEN 'Pending, outside of clearance window'
        WHEN seg.SEGMENT_STATUS_CODE = 'UU'                      THEN 'Waitlisted'
        WHEN seg.SEGMENT_STATUS_CODE IN ('TL', 'HL')            THEN 'Waitlisted, inside of clearance window'
        ELSE 'N/A'
    END::VARCHAR(256) AS SEGMENT_STATUS_DESCRIPTION,
    seg.SEGMENT_ORIGIN,
    seg.SEGMENT_DESTINATION,
    seg.SEGMENT_LOCAL_DEPARTURE_DATE_TIME,
    seg.SEGMENT_LOCAL_ARRIVAL_DATE_TIME,
    seg.SEGMENT_AIRLINE_CODE,
    seg.SEGMENT_FLIGHT_NUMBER,
    tkt.TICKET_NUMBER,
    loy_FQTR.REDEMPTION_MEMBER_NUMBER,
    loy_FQTV.ACCRUAL_MEMBER_NUMBER,
    CASE 
        WHEN RANK() OVER (
            PARTITION BY sr.SERVICE_REQUEST_ID 
            ORDER BY seg.EFFECTIVE_DATE_TIME DESC --NULLS LAST
        ) = 1 
        THEN 1
        ELSE 0 
    END::VARCHAR(5) AS LATEST_FLAG,
    Cast(SHA2(Sr.SERVICE_REQUEST_MEMBER_NUMBER,256)AS VARCHAR(64)) AS Service_Request_Member_Hashkey,
    Cast(SHA2(loy_FQTR.REDEMPTION_MEMBER_NUMBER,256) AS VARCHAR(64)) as Redemption_Member_Hashkey,
    CAST(SHA2(loy_FQTV.ACCRUAL_MEMBER_NUMBER,256) AS VARCHAR(64)) as Accrual_Member_Hashkey
FROM SERVICE_REQUESTS sr

-- FOP is required (JOIN on both SERVICE_REQUEST_ID and PNR_HASHKEY for correctness)
INNER JOIN FARE_ELEMENTS fe
    ON sr.SERVICE_REQUEST_ID = fe.SERV_ID
    AND sr.PNR_HASHKEY = fe.PNR_HASHKEY

-- Latest FOP for each service request
LEFT JOIN LATEST_FOP lf
    ON sr.SERVICE_REQUEST_ID = lf.SERV_ID
    AND sr.PNR_HASHKEY = lf.PNR_HASHKEY

-- Segment details (required if available)
LEFT JOIN SEGMENTS seg
    ON sr.PNR_HASHKEY = seg.PNR_HASHKEY
    AND sr.PRODUCT_ID = seg.SEGMENT_CODE
    AND sr.PASSENGER_ID = seg.PASSENGER_ID
                                                                            
-- Ticket info (optional)
LEFT JOIN TICKETS tkt
    ON sr.PNR_HASHKEY = tkt.PNR_HASHKEY
    AND sr.PASSENGER_ID = tkt.PASSENGER_ID
    AND sr.PRODUCT_ID = tkt.PRODUCT_ID
---Loyalty for FQTR
LEFT JOIN LOYALTY_FQTR loy_FQTR
    ON sr.PNR_HASHKEY = loy_FQTR.PNR_HASHKEY
    AND sr.PASSENGER_ID = loy_FQTR.PASSENGER_ID
 ---Loyalty for FQTV
LEFT JOIN LOYALTY_FQTV loy_FQTV
    ON sr.PNR_HASHKEY = loy_FQTV.PNR_HASHKEY
    AND sr.PASSENGER_ID = loy_FQTV.PASSENGER_ID

QUALIFY DENSE_RANK() OVER (
    PARTITION BY SERVICE_REQUEST_ID
    ORDER BY FOP_EFFECTIVE_DATE_TIME
) = 1
  )
  SELECT DISTINCT
  SERVICE_REQUEST_ID,
PASSENGER_ID,
SERVICE_REQUEST_DATE_TIME,
SERVICE_REQUEST_MEMBER_NUMBER,
SERVICE_ORIGINAL_RBD,
SERVICE_TARGET_RBD,
PNR_UNIQUE_CODE,
SERVICE_REQUEST_FOP_ID,
LATEST_FOP_ID,
SERVICE_REQUEST_DELETION_DATE_TIME,
EFFECTIVE_DATE_TIME,
SEGMENT_CODE,
SEGMENT_STATUS_CODE,
SEGMENT_STATUS_DESCRIPTION,
SEGMENT_ORIGIN,
SEGMENT_DESTINATION,
SEGMENT_LOCAL_DEPARTURE_DATE_TIME,
SEGMENT_LOCAL_ARRIVAL_DATE_TIME,
SEGMENT_AIRLINE_CODE,
SEGMENT_FLIGHT_NUMBER,
TICKET_NUMBER,
REDEMPTION_MEMBER_NUMBER,
ACCRUAL_MEMBER_NUMBER,
LATEST_FLAG,
SERVICE_REQUEST_MEMBER_HASHKEY,
REDEMPTION_MEMBER_HASHKEY,
ACCRUAL_MEMBER_HASHKEY
FROM EUPG_MAIN
;